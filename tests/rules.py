"""Regression checks for service safety, stock transactions and collection."""
from pcshop.model import RepairJob, RuleError

def run_rules(check, output):
    def blocked(call,name):
        try:call()
        except RuleError:check(True,name)
        else:check(False,name)
    def access(j):
        j.disconnect();j.toggle_screw(0);j.toggle_screw(1);j.open_panel()
    def close(j):
        j.close_panel();j.toggle_screw(0);j.toggle_screw(1);j.reconnect()
    j=RepairJob()
    blocked(j.pickup,'Cannot pick up unaccepted PC')
    blocked(j.run_test,'Cannot diagnose unplaced PC')
    blocked(lambda:j.checkout({'upgrade':-1}),'Reject negative order quantity')
    blocked(lambda:j.checkout({'upgrade':9}),'Reject order beyond stock')
    blocked(lambda:j.checkout({'rx6600':8}),'Reject unaffordable order')
    check(j.money==400 and not j.pending,'Rejected orders are atomic')
    j.checkout({'upgrade':1,'incompatible':1})
    check(j.money==300 and not j.inventory,'Payment reserves stock before delivery')
    blocked(j.receive,'Cannot collect undelivered order')
    j.tick(60);j.receive();blocked(j.receive,'Cannot duplicate delivered items')
    j.accept();j.pickup();j.place()
    check(not j.run_test()[0] and j.diagnosed,'Original RAM fault diagnosed')
    blocked(j.open_panel,'Cannot open powered PC');j.disconnect()
    blocked(j.open_panel,'Case screws must be released');j.toggle_screw(0);j.toggle_screw(1);j.open_panel()
    blocked(j.remove_ram,'Both DIMM clips must be released')
    j.toggle_latch(0);blocked(j.remove_ram,'One released clip is insufficient');j.toggle_latch(1);j.remove_ram()
    blocked(lambda:j.install_ram('incompatible'),'DDR5 rejected by DDR4 motherboard')
    check('incompatible' in j.inventory,'Rejected part remains in tray')
    j.install_ram('original');j.toggle_latch(0);j.toggle_latch(1);close(j)
    check(not j.run_test()[0],'Refitting faulty RAM does not repair it')
    access(j);j.toggle_latch(0);j.toggle_latch(1);j.remove_ram();j.install_ram('upgrade');close(j)
    check(not j.run_test()[0],'Diagnostic detects unsecured RAM')
    access(j);j.toggle_latch(0);j.toggle_latch(1);close(j)
    check(j.run_test()[0],'Good RAM passes after clips secured')
    j.complete();check(j.money==300,'Signing off does not pay before collection')
    blocked(j.complete,'Cannot sign off twice');j.pickup();row=j.rack_place()
    check(j.number==2 and j.kind=='RAM upgrade' and len(j.ready)==1,'Table stores PC and opens next request')
    j.collect(row['id']);check(j.money==450 and not j.ready,'Customer collection pays once')
    blocked(lambda:j.collect(row['id']),'Duplicate collection blocked')
    for category,bad,good,kind in [('GPU','faulty_gpu','rx6600','GPU fault'),('Storage','faulty_storage','evo870','Storage fault')]:
        k=RepairJob(kind=kind,installed='replacement');k.hardware[category]=bad;k.inventory=[good]
        k.accept();k.pickup();k.place();check(not k.run_test()[0],category+' fault detected');access(k)
        blocked(lambda:k.remove_part(category),category+' removal blocked by connectors and fasteners')
        cables=['GPU'] if category=='GPU' else ['SATA data','SATA power']
        screws=['GPU screw','GPU latch'] if category=='GPU' else ['Storage screw']
        for c in cables:k.toggle_cable(c)
        for f in screws:k.toggle_fastener(f)
        k.remove_part(category);k.install_part(bad,category)
        for c in cables:k.toggle_cable(c)
        for f in screws:k.toggle_fastener(f)
        close(k);check(not k.run_test()[0],category+' faulty identity persists after reinstall')
        access(k)
        for c in cables:k.toggle_cable(c)
        for f in screws:k.toggle_fastener(f)
        k.remove_part(category);k.install_part(good,category);close(k)
        check(not k.run_test()[0],category+' loose connections detected')
        access(k)
        for c in cables:k.toggle_cable(c)
        for f in screws:k.toggle_fastener(f)
        close(k);check(k.run_test()[0],category+' replacement and reconnection passes')
    k=RepairJob(kind='RAM upgrade',installed='replacement');k.accept();k.pickup();k.place()
    check(not k.run_test()[0],'Working 8 GB does not satisfy 16 GB request')
    j.checkout({'a400':1});j.ready=[row]
    path=output/'test_save.json';j.save(path)
    check(RepairJob.load(path)==j,'Save/load retains money, stock, delivery and collection records')
    path.write_text('{invalid json',encoding='utf-8')
    try:RepairJob.load(path)
    except ValueError:check(True,'Corrupt save rejected')
    else:check(False,'Corrupt save rejected')
    path.unlink()
